#!/usr/bin/env python3
"""Export LaTeX macros so paper prose never hard-codes a number.

Reads data/processed/rates_by_run.csv and paired_<run>.csv and writes
output/macros/results.tex. ``Main`` macros alias the primary compute-matched
run: budget-6 with its harness timeouts re-run (``-retried``) if present, else the
frozen budget-6, else budget-5.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Set

ROOT = Path(__file__).resolve().parents[1]
PROCESSED = ROOT / "data" / "processed"
OUT = ROOT / "output" / "macros" / "results.tex"

RUN_TAGS = {
    "poison-100": "Hundred",
    "poison-yonsei-improved": "YonseiImproved",
    "poison-conditions": "Conditions",
    "poison-budget-4": "BFour",
    "poison-budget-5": "BFive",
    "poison-budget-6": "BSix",
    "poison-budget-6-retried": "BSixR",
    "poison-budget-7": "BSeven",
    "poison-budget-8": "BEight",
}
POSITION_WORDS = {0: "Zero", 1: "One", 2: "Two"}
SELECTION_METRICS = (
    ("acc_actual", "Actual"),
    ("acc_last", "Last"),
    ("acc_uniform", "Uniform"),
    ("acc_random", "Random"),
    ("acc_ast", "Ast"),
)
BEHAVIOR_METRICS = (
    ("no_tool", "NoTool"),
    ("tool_and_gold", "ToolGold"),
    ("no_tool_and_lie", "NoToolLie"),
    ("tool_and_lie", "ToolLie"),
)
FALLBACK_METRICS = (
    ("final_last", "Last"),
    ("final_poisoned_only", "PoisonedOnly"),
    ("acc_poisoned_only", "AccPoisonedOnly"),
    ("acc_other", "AccOther"),
)
SEMANTIC_METRICS = (
    ("ast_hit", "Ast"),
    ("ast_wrong", "AstWrong"),
    ("oracle_hit", "Oracle"),
    ("method_hit", "Method"),
    ("poisoned_fails", "PoisonedFails"),
)
ARM_TAGS = {
    "general-agent-system": "GenOne",
    "general-majority-3": "GenThree",
    "flat-majority-3": "FlatThree",
    "judge-only-3": "JudgeOnly",
    "dag-bpd": "Bpd",
    "dag-yonsei": "Yonsei",
}
SET_TAGS = {"micro_qna": "Qna", "code": "Code"}
METRIC_TAGS = {
    "accurate": "Acc",
    "propagated": "Prop",
    "detection_hit": "Det",
    "recovered": "Rec",
    "lie_emitted": "Emit",
    "detection_given_emitted": "DetEmit",
}
ARM_ORDER = list(ARM_TAGS)
MAIN_CANDIDATES = (
    "poison-budget-7",
    "poison-budget-6-retried",
    "poison-budget-6",
    "poison-budget-5",
)


def rate_macro(run_tag: str, arm: str, task_set: str, metric: str) -> str:
    return "Rate{}{}{}{}".format(
        run_tag, ARM_TAGS[arm], SET_TAGS[task_set], METRIC_TAGS[metric]
    )


def pval_macro(run_tag: str, task_set: str, metric: str, arm_a: str, arm_b: str) -> str:
    first, second = sorted((arm_a, arm_b), key=ARM_ORDER.index)
    return "Pval{}{}{}{}vs{}".format(
        run_tag, SET_TAGS[task_set], METRIC_TAGS[metric], ARM_TAGS[first], ARM_TAGS[second]
    )


def fmt_rate(value: str) -> str:
    return "{:.2f}".format(float(value))


def fmt_p(value: float) -> str:
    """Full relation in math mode, e.g. ``$p=0.008$``; use the macro without extra ``$``."""
    if value < 0.001:
        return "$p<0.001$"
    if value >= 0.995:
        return "$p=1.00$"
    return "$p={:.3f}$".format(value)


def pick_main_run(present: Set[str]) -> Optional[str]:
    for run in MAIN_CANDIDATES:
        if run in present:
            return run
    return None


def _emit(lines: List[str], name: str, value: str) -> None:
    assert re.fullmatch(r"[A-Za-z]+", name), name
    lines.append("\\newcommand{{\\{}}}{{{}}}".format(name, value))


def build_macros(
    rate_rows: Iterable[Dict[str, str]],
    paired: Dict[str, List[Dict[str, str]]],
    position: Optional[Dict[str, List[Dict[str, str]]]] = None,
    semantic: Optional[Dict[str, List[Dict[str, str]]]] = None,
    fallback: Optional[Dict[str, List[Dict[str, str]]]] = None,
    emit: Optional[Dict[str, List[Dict[str, str]]]] = None,
    selection: Optional[Dict[str, List[Dict[str, str]]]] = None,
) -> str:
    rows = [r for r in rate_rows if r.get("condition", "all") == "all"]
    present = {r["run_id"] for r in rows}
    main = pick_main_run(present)
    lines = ["% Auto-generated by code/05_export_macros.py -- do not edit by hand."]
    for run in sorted(present):
        if run not in RUN_TAGS:
            continue
        tags = [RUN_TAGS[run]] + (["Main"] if run == main else [])
        for row in (r for r in rows if r["run_id"] == run):
            arm, task_set = row["system"], row["task_set"]
            if arm not in ARM_TAGS or task_set not in SET_TAGS:
                continue
            for metric in METRIC_TAGS:
                raw = row.get(metric, "")
                if raw in ("", None):
                    continue
                for tag in tags:
                    _emit(lines, rate_macro(tag, arm, task_set, metric), fmt_rate(raw))
            raw_tok = row.get("input_tokens_per_task", "")
            if raw_tok not in ("", None):
                for tag in tags:
                    _emit(
                        lines,
                        "Tok{}{}{}".format(tag, ARM_TAGS[arm], SET_TAGS[task_set]),
                        "{:.1f}".format(float(raw_tok) / 1000.0),
                    )
            for column, suffix in (("n_timeout", "Timeout"), ("n_retried", "Retried")):
                raw_count = row.get(column, "")
                if raw_count not in ("", None):
                    for tag in tags:
                        _emit(
                            lines,
                            "Count{}{}{}{}".format(
                                tag, ARM_TAGS[arm], SET_TAGS[task_set], suffix
                            ),
                            str(int(float(raw_count))),
                        )
            raw_n = row.get("n_lie_emitted", "")
            if raw_n not in ("", None):
                for tag in tags:
                    _emit(
                        lines,
                        "Count{}{}{}Emit".format(tag, ARM_TAGS[arm], SET_TAGS[task_set]),
                        str(int(float(raw_n))),
                    )
    for run, prow in paired.items():
        if run not in RUN_TAGS:
            continue
        tags = [RUN_TAGS[run]] + (["Main"] if run == main else [])
        for r in prow:
            if r["arm_a"] not in ARM_TAGS or r["arm_b"] not in ARM_TAGS:
                continue
            metric = r["metric"]
            if metric not in METRIC_TAGS:
                continue
            for tag in tags:
                _emit(
                    lines,
                    pval_macro(tag, r["task_set"], metric, r["arm_a"], r["arm_b"]),
                    fmt_p(float(r["p_value"])),
                )
    pval_done: Set[str] = set()
    for run, prows in (position or {}).items():
        if run not in RUN_TAGS:
            continue
        tag = RUN_TAGS[run]
        for r in prows:
            arm, task_set = r["system"], r["task_set"]
            if arm not in ARM_TAGS or task_set not in SET_TAGS:
                continue
            word = POSITION_WORDS[int(float(r["position"]))]
            for column, metric in (("accurate", "accurate"), ("propagated", "propagated"),
                                   ("detection_hit", "detection_hit"), ("recovered", "recovered")):
                if r.get(column, "") in ("", None):
                    continue
                base = "{}{}{}{}".format(tag, ARM_TAGS[arm], SET_TAGS[task_set], METRIC_TAGS[metric])
                _emit(lines, "RatePos" + base + word, fmt_rate(r[column]))
                pval = r.get("perm_p_{}".format(column), "")
                if pval not in ("", None) and base not in pval_done:
                    pval_done.add(base)
                    _emit(lines, "PvalPos" + base, fmt_p(float(pval)))
    for run, srows in (semantic or {}).items():
        if run not in RUN_TAGS:
            continue
        tags = [RUN_TAGS[run]] + (["Main"] if run == main else [])
        for r in srows:
            arm = r["system"]
            if arm not in ARM_TAGS:
                continue
            for column, suffix in SEMANTIC_METRICS:
                if r.get(column, "") in ("", None):
                    continue
                for tag in tags:
                    _emit(
                        lines,
                        "RateSem{}{}Code{}".format(tag, ARM_TAGS[arm], suffix),
                        fmt_rate(r[column]),
                    )
            for tag in tags:
                _emit(lines, "CountSem{}{}CodeN".format(tag, ARM_TAGS[arm]), str(int(float(r["n"]))))
                if r.get("p_method_vs_ast", "") not in ("", None):
                    _emit(
                        lines,
                        "PvalSem{}{}CodeMethodVsAst".format(tag, ARM_TAGS[arm]),
                        fmt_p(float(r["p_method_vs_ast"])),
                    )
    for run, frows in (fallback or {}).items():
        if run not in RUN_TAGS:
            continue
        tags = [RUN_TAGS[run]] + (["Main"] if run == main else [])
        for r in frows:
            arm = r["system"]
            if arm not in ARM_TAGS:
                continue
            for column, suffix in FALLBACK_METRICS:
                if r.get(column, "") in ("", None):
                    continue
                for tag in tags:
                    _emit(lines, "RateFb{}{}Code{}".format(tag, ARM_TAGS[arm], suffix), fmt_rate(r[column]))
            if r.get("final_poisoned_only_k", "") not in ("", None):
                for tag in tags:
                    _emit(
                        lines,
                        "CountFb{}{}CodePoisonedOnly".format(tag, ARM_TAGS[arm]),
                        str(int(float(r["final_poisoned_only_k"]))),
                    )
    for run, erows in (emit or {}).items():
        if run not in RUN_TAGS:
            continue
        tag = RUN_TAGS[run]
        for r in erows:
            arm = r["system"]
            if arm not in ARM_TAGS:
                continue
            for column, suffix in BEHAVIOR_METRICS:
                if r.get(column, "") in ("", None):
                    continue
                _emit(
                    lines,
                    "RateBeh{}{}Qna{}".format(tag, ARM_TAGS[arm], suffix),
                    fmt_rate(r[column]),
                )
    for run, srows in (selection or {}).items():
        if run not in RUN_TAGS:
            continue
        tags = [RUN_TAGS[run]] + (["Main"] if run == main else [])
        for r in srows:
            arm = r["system"]
            if arm not in ARM_TAGS:
                continue
            for column, suffix in SELECTION_METRICS:
                if r.get(column, "") in ("", None):
                    continue
                for tag in tags:
                    _emit(
                        lines,
                        "RateSel{}{}Code{}".format(tag, ARM_TAGS[arm], suffix),
                        fmt_rate(r[column]),
                    )
    if main:
        _emit(lines, "MainRunName", main.replace("poison-", ""))
    return "\n".join(lines) + "\n"


def main() -> None:
    with (PROCESSED / "rates_by_run.csv").open(encoding="utf-8", newline="") as handle:
        rate_rows = list(csv.DictReader(handle))
    paired: Dict[str, List[Dict[str, str]]] = {}
    for path in sorted(PROCESSED.glob("paired_*.csv")):
        run_id = path.stem[len("paired_"):]
        with path.open(encoding="utf-8", newline="") as handle:
            paired[run_id] = list(csv.DictReader(handle))
    position: Dict[str, List[Dict[str, str]]] = {}
    for path in sorted(PROCESSED.glob("position_*.csv")):
        run_id = path.stem[len("position_"):]
        with path.open(encoding="utf-8", newline="") as handle:
            position[run_id] = list(csv.DictReader(handle))
    semantic: Dict[str, List[Dict[str, str]]] = {}
    for path in sorted(PROCESSED.glob("semantic_baselines_*.csv")):
        run_id = path.stem[len("semantic_baselines_"):]
        with path.open(encoding="utf-8", newline="") as handle:
            semantic[run_id] = list(csv.DictReader(handle))
    fallback: Dict[str, List[Dict[str, str]]] = {}
    for path in sorted(PROCESSED.glob("fallback_*.csv")):
        run_id = path.stem[len("fallback_"):]
        with path.open(encoding="utf-8", newline="") as handle:
            fallback[run_id] = list(csv.DictReader(handle))
    emit: Dict[str, List[Dict[str, str]]] = {}
    for path in sorted(PROCESSED.glob("qna_emit_behavior_*.csv")):
        run_id = path.stem[len("qna_emit_behavior_"):]
        with path.open(encoding="utf-8", newline="") as handle:
            emit[run_id] = list(csv.DictReader(handle))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    selection: Dict[str, List[Dict[str, str]]] = {}
    for path in sorted(PROCESSED.glob("selection_*.csv")):
        run_id = path.stem[len("selection_"):]
        with path.open(encoding="utf-8", newline="") as handle:
            selection[run_id] = list(csv.DictReader(handle))
    OUT.write_text(
        build_macros(rate_rows, paired, position, semantic, fallback, emit, selection),
        encoding="utf-8",
    )
    print("wrote", OUT)


if __name__ == "__main__":
    main()
