#!/usr/bin/env python3
"""Export booktabs TeX tables from processed poison rates."""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "data" / "processed" / "rates_by_run.csv"
OUT = ROOT / "output" / "tables"
METRICS = ("accurate", "propagated", "detection_hit", "recovered")
LABELS = {
    "accurate": "Acc.",
    "propagated": "Prop.",
    "detection_hit": "Det.",
    "recovered": "Rec.",
}


def load_rows() -> List[Dict[str, str]]:
    with CSV_PATH.open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def fmt(rate: float, lo: float, hi: float) -> str:
    return "{:.3f} [{:.3f}, {:.3f}]".format(rate, lo, hi)


def lookup(
    rows: List[Dict[str, str]],
    run_id: str,
    system: str,
    task_set: str,
    condition: str = "all",
) -> Optional[Dict[str, str]]:
    for row in rows:
        row_cond = row.get("condition", "all")
        if (
            row["run_id"] == run_id
            and row["system"] == system
            and row["task_set"] == task_set
            and row_cond == condition
        ):
            return row
    for row in rows:
        if (
            row["run_id"] == run_id
            and row["system"] == system
            and row["task_set"] == task_set
            and "condition" not in row
        ):
            return row
    return None


def metric_cell(row: Dict[str, str], key: str) -> str:
    return fmt(
        float(row[key]),
        float(row["{}_ci_low".format(key)]),
        float(row["{}_ci_high".format(key)]),
    )


def tabular(headers: List[str], body_rows: List[List[str]], caption: str, label: str) -> str:
    cols = "l" + "c" * (len(headers) - 1)
    lines = [
        "% Auto-generated by code/03_export_paper_tables.py — do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\scriptsize",
        "\\caption{" + caption + "}",
        "\\label{" + label + "}",
        "\\begin{tabular}{" + cols + "}",
        "\\toprule",
        " & ".join(headers) + " \\\\",
        "\\midrule",
    ]
    for row in body_rows:
        lines.append(" & ".join(row) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    return "\n".join(lines)


def export_main_agent(rows: List[Dict[str, str]]) -> str:
    systems = ["dag-bpd", "dag-yonsei", "general-agent-system"]
    headers = ["System", "Set"] + [LABELS[m] for m in METRICS]
    body: List[List[str]] = []
    for system in systems:
        for task_set, short in (("micro_qna", "QnA"), ("code", "Code")):
            row = lookup(rows, "poison-100", system, task_set)
            if row is None:
                continue
            body.append([system, short] + [metric_cell(row, m) for m in METRICS])
    return tabular(
        headers,
        body,
        "Main agent-condition rates on poison-100 ($n{=}100$ per cell). "
        "Cells show rate with bootstrap 95\\% CI (seed 20260909). "
        "Not an Index score.",
        "tab:main-agent",
    )


def export_yonsei_ab(rows: List[Dict[str, str]]) -> str:
    headers = ["Version", "Set"] + [LABELS[m] for m in METRICS]
    body: List[List[str]] = []
    pairs: List[Tuple[str, str, str]] = [
        ("poison-100", "dag-yonsei", "naive"),
        ("poison-yonsei-improved", "dag-yonsei", "source-first"),
    ]
    for run_id, system, name in pairs:
        for task_set, short in (("micro_qna", "QnA"), ("code", "Code")):
            row = lookup(rows, run_id, system, task_set)
            if row is None:
                continue
            body.append([name, short] + [metric_cell(row, m) for m in METRICS])
    return tabular(
        headers,
        body,
        "Exploratory yonsei A/B: naive scan trust vs source-over-scan rule "
        "(same model and strong agent injection).",
        "tab:yonsei-ab",
    )


def export_weak_strong(rows: List[Dict[str, str]]) -> str:
    headers = ["Run", "Set", "BPD Det.", "BPD Prop.", "Yonsei Prop."]
    body: List[List[str]] = []
    for run_id, name in (("poison-20", "weak-20"), ("poison-100", "strong-100")):
        for task_set, short in (("micro_qna", "QnA"), ("code", "Code")):
            bpd = lookup(rows, run_id, "dag-bpd", task_set)
            yon = lookup(rows, run_id, "dag-yonsei", task_set)
            if bpd is None or yon is None:
                continue
            body.append(
                [
                    name,
                    short,
                    metric_cell(bpd, "detection_hit"),
                    metric_cell(bpd, "propagated"),
                    metric_cell(yon, "propagated"),
                ]
            )
    return tabular(
        headers,
        body,
        "Exploratory contrast: weak injection (poison-20) vs strong injection (poison-100).",
        "tab:weak-vs-strong",
    )


def export_condition_ablation(rows: List[Dict[str, str]]) -> Optional[str]:
    present = [
        r
        for r in rows
        if r["run_id"] == "poison-conditions"
        and r.get("condition") in ("none", "document", "agent")
    ]
    if not present:
        return None
    headers = ["System", "Cond.", "Set"] + [LABELS[m] for m in METRICS]
    body: List[List[str]] = []
    order = ("none", "document", "agent")
    systems = sorted({r["system"] for r in present})
    for system in systems:
        for cond in order:
            for task_set, short in (("micro_qna", "QnA"), ("code", "Code")):
                row = lookup(rows, "poison-conditions", system, task_set, cond)
                if row is None:
                    continue
                body.append(
                    [system, cond, short] + [metric_cell(row, m) for m in METRICS]
                )
    return tabular(
        headers,
        body,
        "Condition ablation on the 100+100 suite (none / document / agent). "
        "Rates with bootstrap 95\\% CI.",
        "tab:condition-ablation",
    )


MAIN_RUN_CANDIDATES = ("poison-budget-6-retried", "poison-budget-6", "poison-budget-5")
BUDGET_ARMS = (
    ("general-agent-system", "general-1"),
    ("general-majority-3", "general-3 maj."),
    ("flat-majority-3", "flat-3 maj."),
    ("judge-only-3", "judge-only-3"),
    ("dag-bpd", "dag-bpd"),
)


def export_budget(rows: List[Dict[str, str]], run_id: str, caption: str, label: str) -> Optional[str]:
    run_rows = [r for r in rows if r["run_id"] == run_id and r.get("condition", "all") == "all"]
    has_emit = any((r.get("lie_emitted") or "") != "" for r in run_rows)
    headers = ["Arm", "Set"] + [LABELS[m] for m in METRICS]
    if has_emit:
        headers += ["Emit.", "Det$\\mid$Emit"]
    headers += ["In-tok/task (k)"]
    body: List[List[str]] = []
    for system, name in BUDGET_ARMS:
        for task_set, short in (("micro_qna", "QnA"), ("code", "Code")):
            row = lookup(rows, run_id, system, task_set)
            if row is None:
                continue
            raw = row.get("input_tokens_per_task") or ""
            tokens = "{:.1f}".format(float(raw) / 1000.0) if raw else "--"
            cells = [name, short] + [metric_cell(row, m) for m in METRICS]
            if has_emit:
                emit = row.get("lie_emitted") or ""
                cond = row.get("detection_given_emitted") or ""
                cells.append("{:.3f}".format(float(emit)) if emit else "--")
                cells.append("{:.3f}".format(float(cond)) if cond else "--")
            cells.append(tokens)
            body.append(cells)
    if not body:
        return None
    return tabular(headers, body, caption, label)


def export_compact(rows: List[Dict[str, str]], run_id: str, caption: str, label: str) -> Optional[str]:
    """Paper-width table: one row per arm, two decimals, no CIs (CIs live in tab_budget*.tex)."""
    run_rows = [r for r in rows if r["run_id"] == run_id and r.get("condition", "all") == "all"]
    has_emit = any((r.get("lie_emitted") or "") != "" for r in run_rows)
    sub = ["Acc", "Prop", "Det", "Rec"] + (["Emit", "Det$\\mid$E"] if has_emit else [])
    body: List[List[str]] = []
    for system, name in BUDGET_ARMS:
        cells = [name]
        found = False
        for task_set in ("micro_qna", "code"):
            row = lookup(rows, run_id, system, task_set)
            if row is None:
                cells += ["--"] * len(sub)
                continue
            found = True
            for key in ("accurate", "propagated", "detection_hit", "recovered"):
                cells.append("{:.2f}".format(float(row[key])))
            if has_emit:
                emit = row.get("lie_emitted") or ""
                cond = row.get("detection_given_emitted") or ""
                cells.append("{:.2f}".format(float(emit)) if emit else "--")
                cells.append("{:.2f}".format(float(cond)) if cond else "--")
        if found:
            body.append(cells)
    if not body:
        return None
    width = len(sub)
    lines = [
        "% Auto-generated by code/03_export_paper_tables.py -- do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{" + caption + "}",
        "\\label{" + label + "}",
        "\\begin{tabular}{l" + "c" * (2 * width) + "}",
        "\\toprule",
        " & \\multicolumn{" + str(width) + "}{c}{QnA} & \\multicolumn{" + str(width) + "}{c}{Code} \\\\",
        "\\cmidrule(lr){2-" + str(width + 1) + "}\\cmidrule(lr){" + str(width + 2) + "-" + str(2 * width + 1) + "}",
        "Arm & " + " & ".join(sub + sub) + " \\\\",
        "\\midrule",
    ]
    for cells in body:
        lines.append(" & ".join(cells) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    return "\n".join(lines)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    rows = load_rows()
    mapping = {
        "tab_main_agent.tex": export_main_agent(rows),
        "tab_yonsei_ab.tex": export_yonsei_ab(rows),
        "tab_weak_vs_strong.tex": export_weak_strong(rows),
    }
    pilot = export_budget(
        rows,
        "poison-budget-4",
        "Compute-matched pilot (core $n{=}20$ per cell, legacy injection wording). "
        "Rates with bootstrap 95\\% CI.",
        "tab:budget4-pilot",
    )
    if pilot:
        mapping["tab_budget4_pilot.tex"] = pilot
    budget5 = export_budget(
        rows,
        "poison-budget-5",
        "Compute-matched arms with aligned wording ($n{=}100$ per cell, agent condition). "
        "Here the claim reaches the single loop and general-3 as a user message, and the "
        "other arms in the system prompt (superseded by the main run). Rates with "
        "bootstrap 95\\% CI; last column is mean input tokens per task.",
        "tab:budget5",
    )
    if budget5:
        mapping["tab_budget5.tex"] = budget5
    budget6 = export_budget(
        rows,
        "poison-budget-6",
        "Compute-matched arms with the identical claim injected through the system "
        "prompt of every arm ($n{=}100$ per cell, agent condition). Emit.: share of "
        "runs in which the poisoned replica itself output the lie; Det$\\mid$Emit: "
        "attribution rate among those runs. Rates with bootstrap 95\\% CI.",
        "tab:budget6",
    )
    if budget6:
        mapping["tab_budget6.tex"] = budget6
    budget6r = export_budget(
        rows,
        "poison-budget-6-retried",
        "Same run as Table~\\ref{tab:budget6} after re-running the tasks that hit the "
        "60\\,s harness limit (identical configuration; see text). $n{=}100$ per cell, "
        "agent condition. Rates with bootstrap 95\\% CI.",
        "tab:budget6-retried",
    )
    if budget6r:
        mapping["tab_budget6_retried.tex"] = budget6r
    present_runs = {r["run_id"] for r in rows}
    main_run = next((r for r in MAIN_RUN_CANDIDATES if r in present_runs), None)
    if main_run:
        compact = export_compact(
            rows,
            main_run,
            "Compute-matched arms under the same injected claim ($n{=}100$ per cell, agent "
            "condition; run \\texttt{" + main_run.replace("poison-", "") + "}). Acc.: gold answer; "
            "Prop.: lie in final output; Det.: poisoned source named; Rec.: Det.\\ and Acc.; "
            "Emit: poisoned replica output the lie; Det$\\mid$E: Det.\\ among Emit runs.",
            "tab:main",
        )
        if compact:
            mapping["tab_main_compact.tex"] = compact
    abl = export_condition_ablation(rows)
    if abl:
        mapping["tab_condition_ablation.tex"] = abl
    for name, text in mapping.items():
        path = OUT / name
        path.write_text(text, encoding="utf-8")
        print("wrote", path)


if __name__ == "__main__":
    main()
