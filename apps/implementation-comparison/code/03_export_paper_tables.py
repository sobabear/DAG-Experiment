def export_budget(rows: List[Dict[str, str]], run_id: str, caption: str, label: str) -> Optional[str]:
    run_rows = [r for r in rows if r["run_id"] == run_id and r.get("condition", "all") == "all"]
    has_emit = any((r.get("lie_emitted") or "") != "" for r in run_rows)
    headers = ["Arm", "Set"] + [LABELS[m] for m in METRICS]
    if has_emit:
        headers += ["Emit.", "Det$\\mid$Emit"]
    headers += ["In-tok/task (k)"]
    body: List[List[str]] = []
    for system, name in BUDGET_ARMS:
        for task_set, short in (("micro_qna", "QnA"), ("code", "Code")):
            row = lookup(rows, run_id, system, task_set)
            if row is None:
                continue
            raw = row.get("input_tokens_per_task") or ""
            tokens = "{:.1f}".format(float(raw) / 1000.0) if raw else "--"
            cells = [name, short] + [metric_cell(row, m) for m in METRICS]
            if has_emit:
                emit = row.get("lie_emitted") or ""
                cond = row.get("detection_given_emitted") or ""
                cells.append("{:.3f}".format(float(emit)) if emit else "--")
                cells.append("{:.3f}".format(float(cond)) if cond else "--")
            cells.append(tokens)
            body.append(cells)
    if not body:
        return None
    return tabular(headers, body, caption, label)


def export_compact(rows: List[Dict[str, str]], run_id: str, caption: str, label: str) -> Optional[str]:
    """Paper-width table: one row per arm, two decimals, no CIs (CIs live in tab_budget*.tex)."""
    run_rows = [r for r in rows if r["run_id"] == run_id and r.get("condition", "all") == "all"]
    has_emit = any((r.get("lie_emitted") or "") != "" for r in run_rows)
    sub = ["Acc", "Prop", "Det", "Rec"] + (["Emit", "Det$\\mid$E"] if has_emit else [])
    body: List[List[str]] = []
    for system, name in BUDGET_ARMS:
        cells = [name]
        found = False
        for task_set in ("micro_qna", "code"):
            row = lookup(rows, run_id, system, task_set)
            if row is None:
                cells += ["--"] * len(sub)
                continue
            found = True
            for key in ("accurate", "propagated", "detection_hit", "recovered"):
                cells.append("{:.2f}".format(float(row[key])))
            if has_emit:
                emit = row.get("lie_emitted") or ""
                cond = row.get("detection_given_emitted") or ""
                cells.append("{:.2f}".format(float(emit)) if emit else "--")
                cells.append("{:.2f}".format(float(cond)) if cond else "--")
        if found:
            body.append(cells)
    if not body:
        return None
    width = len(sub)
    lines = [
        "% Auto-generated by code/03_export_paper_tables.py -- do not edit by hand.",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\caption{" + caption + "}",
        "\\label{" + label + "}",
        "\\begin{tabular}{l" + "c" * (2 * width) + "}",
        "\\toprule",
        " & \\multicolumn{" + str(width) + "}{c}{QnA} & \\multicolumn{" + str(width) + "}{c}{Code} \\\\",
        "\\cmidrule(lr){2-" + str(width + 1) + "}\\cmidrule(lr){" + str(width + 2) + "-" + str(2 * width + 1) + "}",
        "Arm & " + " & ".join(sub + sub) + " \\\\",
        "\\midrule",
    ]
    for cells in body:
        lines.append(" & ".join(cells) + " \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    return "\n".join(lines)


def export_position(
    rows: List[Dict[str, str]], run_id: str, caption: str, label: str
) -> Optional[str]:
    """Recovery and detection by which replica carried the lie, with permutation p."""
    run_rows = [r for r in rows if r["run_id"] == run_id]
    if not run_rows:
        return None
    headers = ["Arm", "Set"] + ["Acc@{}".format(k) for k in (0, 1, 2)] + ["$p_{\\mathrm{Acc}}$"]
    headers += ["Rec@{}".format(k) for k in (0, 1, 2)] + ["$p_{\\mathrm{Rec}}$"]
    body: List[List[str]] = []
    for system, name in BUDGET_ARMS:
        for task_set, short in (("micro_qna", "QnA"), ("code", "Code")):
            cells_for = {
                int(float(r["position"])): r
                for r in run_rows
                if r["system"] == system and r["task_set"] == task_set
            }
            if not cells_for:
                continue
            cells = [name, short]
            for column in ("accurate", "recovered"):
                for k in (0, 1, 2):
                    row = cells_for.get(k)
                    cells.append("{:.2f}".format(float(row[column])) if row else "--")
                any_row = next(iter(cells_for.values()))
                p_value = float(any_row["perm_p_{}".format(column)])
                cells.append("$<$0.001" if p_value < 0.001 else "{:.3f}".format(p_value))
            body.append(cells)
    if not body:
        return None
    return tabular(headers, body, caption, label)


def export_semantic(
    rows: List[Dict[str, str]], run_id: str, caption: str, label: str
) -> Optional[str]:
    """Judge-free attribution on code replicas versus each arm's own detection."""
    run_rows = {r["system"]: r for r in rows if r["run_id"] == run_id}
    if not run_rows:
        return None
    headers = ["Arm", "$n$", "AST outlier", "AST wrong", "Test oracle", "Arm detection"]
    body: List[List[str]] = []
    for system, name in BUDGET_ARMS:
        row = run_rows.get(system)
        if row is None:
            continue
        cells = [name, str(int(float(row["n"])))]
        for column in ("ast_hit", "ast_wrong", "oracle_hit", "method_hit"):
            raw = row.get(column, "")
            cells.append("{:.2f}".format(float(raw)) if raw not in ("", None) else "--")
        body.append(cells)
    if not body:
        return None
    return tabular(headers, body, caption, label)


def export_fallback(
    rows_a: List[Dict[str, str]], rows_b: List[Dict[str, str]], caption: str, label: str
) -> Optional[str]:
    """Which replica each three-replica arm promotes on code tasks, for two models."""
    if not rows_a and not rows_b:
        return None
    headers = ["Arm"]
    for tag in ("A", "B"):
        headers += ["Last " + tag, "Poisoned " + tag, "Acc. poisoned " + tag, "Acc. other " + tag]
    body: List[List[str]] = []
    for system, name in BUDGET_ARMS:
        found = False
        cells = [name]
        for rows in (rows_a, rows_b):
            row = next((r for r in rows if r["system"] == system), None)
            if row is None:
                cells += ["--"] * 4
                continue
            found = True
            cells += [
                "{:.2f}".format(float(row["final_last"])),
                "{:.2f}".format(float(row["final_poisoned_only"])),
                "{:.2f}".format(float(row["acc_poisoned_only"])),
                "{:.2f}".format(float(row["acc_other"])),
            ]
        if found:
            body.append(cells)
    if not body:
        return None
    return tabular(headers, body, caption, label)


